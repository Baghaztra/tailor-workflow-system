CREATE TABLE workers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    specialization VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT workers_specialization_check
        CHECK (specialization IN ('CUTTING', 'SEWING', 'FINISHING'))
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    stage VARCHAR(20),
    total_price NUMERIC(12, 2),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT orders_status_check
        CHECK (status IN ('CREATED', 'IN_PROGRESS', 'READY_FOR_PICKUP', 'PICKED_UP', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT orders_stage_check
        CHECK (stage IN ('CUTTING', 'SEWING', 'FINISHING'))
);

CREATE TABLE order_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    worker_id BIGINT,
    stage VARCHAR(20),
    action VARCHAR(20) NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT order_logs_action_check
        CHECK (action IN ('CREATED', 'ASSIGNED', 'STARTED', 'COMPLETED', 'READY_FOR_PICKUP',
                          'PICKED_UP', 'PAYMENT_RECORDED', 'CANCELLED')),
    CONSTRAINT order_logs_stage_check
        CHECK (stage IN ('CUTTING', 'SEWING', 'FINISHING')),
    CONSTRAINT fk_order_logs_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_logs_worker FOREIGN KEY (worker_id) REFERENCES workers (id)
);

CREATE INDEX idx_order_logs_order_id ON order_logs (order_id);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    method VARCHAR(20) NOT NULL,
    paid_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payments_order UNIQUE (order_id),
    CONSTRAINT payments_method_check CHECK (method IN ('CASH', 'TRANSFER')),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

CREATE TABLE auth_sessions (
    id VARCHAR(64) PRIMARY KEY,
    refresh_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_key VARCHAR(255) NOT NULL,
    attempted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_login_attempts_key_time ON login_attempts (attempt_key, attempted_at);
